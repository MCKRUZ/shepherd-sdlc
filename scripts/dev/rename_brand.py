#!/usr/bin/env python3
"""Replay the Shepherd brand rename over the plugin tree.

The fork brands the plugin **Shepherd**: the plugin id becomes ``shepherd`` (installed as
``shepherd@mckruz``, repository ``MCKRUZ/shepherd-sdlc``), the 32 slash commands move from
``/sdlc`` / ``/sdlc-<x>`` to ``/sprd`` / ``/sprd-<x>``, the session-start hook files and their
``[SDLC…]`` markers become ``shepherd-session-start.*`` and ``[SHEPHERD…]``. Everything a project
*stores* — the ``.sdlc/`` directory, ``specs/``, the ledgers, gate ids, exit-gate wording, the
``sdlc-orchestrator`` agent, and "SDLC" where it names the methodology — stays exactly as it is.

Upstream (``MCKRUZ/claude-code-sdlc``) keeps the old names, so every upstream sync re-introduces
them. This script is the replay: run it after a sync and the tree is Shepherd again. It is
re-runnable — a file already moved is skipped, a substitution already made matches nothing.

    python3 scripts/dev/rename_brand.py            # apply
    python3 scripts/dev/rename_brand.py --dry-run  # report what would change, write nothing
    python3 scripts/dev/rename_brand.py --skip-lock  # apply, but do not run `uv lock`
    python3 scripts/dev/rename_brand.py --studio     # also rewrite the desktop app under studio/

What it does, in order:

  a) ``git mv commands/sdlc*.md -> commands/sprd*.md`` and
     ``git mv hooks/sdlc-session-start.{sh,ps1} -> hooks/shepherd-session-start.{sh,ps1}``
     (``git mv`` keeps the executable bit).
  b) Over ``git ls-files`` minus the excluded paths (Studio, brand assets, proposals, specs,
     the CHANGELOG history, the harness — regenerated by ``sync_kit.py`` — binaries and lock
     files), rewrite each file as BYTES so line endings are untouched:
       1. slash commands        ``(?<![\\w./~])/sdlc\\b`` -> ``/sprd``
       2. command file names    ``commands/sdlc`` -> ``commands/sprd``; ``command: sdlc-`` ->
                                ``sprd-``; anchors ``(#sdlc-`` -> ``(#sprd-``; quoted
                                ``"sdlc-<cmd>.md"`` -> ``sprd-`` (command stems only, so
                                ``sdlc-orchestrator.md`` is never touched); the
                                ``"sdlc-…`` tuple strings in ``test_activities_model.py``
       3. hook names            ``sdlc-session-start`` -> ``shepherd-session-start``
       4. hook markers          ``[SDLC]``, ``[SDLC-…]``, ``[/SDLC-…]`` -> ``[SHEPHERD…]``
                                (``[SDLC profile being used]``, a template placeholder, is not
                                a marker and is left alone)
       5. plugin id             ``MCKRUZ/claude-code-sdlc`` -> ``MCKRUZ/shepherd-sdlc``, then
                                ``claude-code-sdlc@mckruz`` -> ``shepherd@mckruz``, then
                                ``claude-code-sdlc:`` -> ``shepherd:``, then bare
                                ``claude-code-sdlc`` -> ``shepherd`` (every bare site is printed
                                so the prose around it can be reviewed by hand)
       6. ``scripts/pyproject.toml``: ``claude-code-sdlc-scripts`` -> ``shepherd-scripts``,
          then ``uv lock --project scripts`` so ``uv.lock`` follows.
  c) Print counts per rule and the RESIDUALS — what still matches ``/sdlc``,
     ``claude-code-sdlc``, ``[SDLC`` or ``sdlc-session-start`` in the non-excluded tracked tree.
  d) With ``--studio`` only: a second pass over the tracked files under ``studio/`` (skipping
     ``node_modules``, ``dist``, ``build`` and ``public/brand``), as bytes, with the rules a
     Studio file can carry — the slash commands (rule 1), ``commands/sdlc`` paths and the
     quoted fixture forms ``command: 'sdlc-`` / ``'sdlc-<cmd>.md'`` (rules 2a, 2b, 2d), the
     agent namespace ``claude-code-sdlc:`` (rule 5c) and ``pluginName: 'claude-code-sdlc'``.
     Never the bare id: ``LEGACY_PLUGIN_IDS`` in ``studio/shared/pluginId.ts`` names
     ``claude-code-sdlc`` on purpose, so the cache scan still finds a pre-2.0 install. Studio's
     internals (``sdlc-studio``, ``studio.*`` keys, ``[Studio]``, the MCP server name) match
     none of these rules. Its residuals are reported on their own line.

It is a rename, not a refactor: no script's exit codes or JSON shapes change. It never commits.
Plain Python 3.12 standard library; no dependencies.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# --- scope --------------------------------------------------------------------------------------

EXCLUDED_DIRS = (
    "studio/",          # the desktop app — its own wave
    "docs/brand/",      # brand assets, generated
    "docs/proposals/",  # history
    "specs/",           # history
    "scripts/dev/",     # this script
    "harness/",         # regenerated by scripts/sync_kit.py
)
EXCLUDED_FILES = (
    "CHANGELOG.md",       # past entries speak for their own release
    "scripts/.coverage",  # binary, untracked separately
    "scripts/sync_kit.py",
    "scripts/tests/test_sync_kit.py",  # pins the upstream strings sync_kit.py rewrites
)
EXCLUDED_SUFFIXES = (".png", ".ico", ".icns", ".webp", ".jpg", ".pdf", ".pptx", ".lock")

# --studio: the desktop app, otherwise excluded above. Tracked files only, so node_modules/ and
# dist/ never appear; listed anyway so an accidentally tracked build never gets rewritten.
STUDIO_DIR = "studio/"
STUDIO_EXCLUDED_DIRS = (
    "studio/node_modules/",
    "studio/dist/",
    "studio/dist-electron/",
    "studio/build/",         # packaging assets (icons) — the visual wave
    "studio/public/brand/",  # generated brand SVGs — regenerated by their own test
)

PYPROJECT = "scripts/pyproject.toml"
ACTIVITIES_TEST = "scripts/tests/test_activities_model.py"

HOOK_MOVES = (
    ("hooks/sdlc-session-start.sh", "hooks/shepherd-session-start.sh"),
    ("hooks/sdlc-session-start.ps1", "hooks/shepherd-session-start.ps1"),
)

# Residual patterns — what a clean tree must no longer contain (outside the excluded paths).
RESIDUAL_PATTERNS = (
    ("/sdlc", re.compile(rb"(?<![\w./~])/sdlc\b")),
    ("claude-code-sdlc", re.compile(rb"claude-code-sdlc")),
    ("[SDLC", re.compile(rb"\[SDLC")),
    ("sdlc-session-start", re.compile(rb"sdlc-session-start")),
)
# Under studio/ the bare id is allowed (LEGACY_PLUGIN_IDS), so only the forms the pass rewrites.
STUDIO_RESIDUAL_PATTERNS = (
    ("/sdlc", re.compile(rb"(?<![\w./~])/sdlc\b")),
    ("claude-code-sdlc:", re.compile(rb"claude-code-sdlc:")),
    ("pluginName: 'claude-code-sdlc'", re.compile(rb"pluginName: 'claude-code-sdlc'")),
)


def git(*args: str) -> str:
    proc = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, check=True)
    return proc.stdout.decode("utf-8", errors="replace")


def tracked_files() -> list[str]:
    out = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, check=True).stdout
    return [p.decode("utf-8") for p in out.split(b"\0") if p]


def excluded(path: str) -> bool:
    if path in EXCLUDED_FILES:
        return True
    if path.startswith(EXCLUDED_DIRS):
        return True
    return path.lower().endswith(EXCLUDED_SUFFIXES)


def studio_excluded(path: str) -> bool:
    """The --studio pass's scope: tracked files under studio/ that are neither build output,
    brand assets nor binaries."""
    if not path.startswith(STUDIO_DIR):
        return True
    if path.startswith(STUDIO_EXCLUDED_DIRS):
        return True
    return path.lower().endswith(EXCLUDED_SUFFIXES)


def is_binary(data: bytes) -> bool:
    return b"\0" in data[:8192]


def line_of(data: bytes, offset: int) -> int:
    return data.count(b"\n", 0, offset) + 1


def line_text(data: bytes, offset: int) -> str:
    start = data.rfind(b"\n", 0, offset) + 1
    end = data.find(b"\n", offset)
    if end == -1:
        end = len(data)
    return data[start:end].decode("utf-8", errors="replace").rstrip("\r")


# --- a) moves -----------------------------------------------------------------------------------

def command_moves() -> list[tuple[str, str]]:
    """Every command file under either prefix, as (old, new) — so a file already moved is counted
    as in place rather than forgotten."""
    moves = {}
    for src in (ROOT / "commands").glob("sdlc*.md"):
        moves[src.name[len("sdlc"):]] = (f"commands/{src.name}", f"commands/sprd{src.name[len('sdlc'):]}")
    for dst in (ROOT / "commands").glob("sprd*.md"):
        moves.setdefault(dst.name[len("sprd"):], (f"commands/sdlc{dst.name[len('sprd'):]}", f"commands/{dst.name}"))
    return [moves[k] for k in sorted(moves)]


def apply_moves(moves: list[tuple[str, str]], dry_run: bool) -> tuple[int, int]:
    moved = skipped = 0
    for src, dst in moves:
        src_exists = (ROOT / src).exists()
        dst_exists = (ROOT / dst).exists()
        if src_exists and dst_exists:
            sys.exit(f"error: both {src} and {dst} exist — resolve by hand before re-running")
        if not src_exists and dst_exists:
            skipped += 1
            continue
        if not src_exists:
            sys.exit(f"error: neither {src} nor {dst} exists")
        if dry_run:
            print(f"  would git mv {src} -> {dst}")
        else:
            git("mv", src, dst)
        moved += 1
    return moved, skipped


def command_suffixes() -> list[str]:
    """``""``, ``"-setup"``, ``"-spec-status"``, … — from whichever prefix the files carry now."""
    suffixes = set()
    for prefix in ("sdlc", "sprd"):
        for p in (ROOT / "commands").glob(f"{prefix}*.md"):
            suffixes.add(p.stem[len(prefix):])
    # Longest first so the alternation cannot stop at a shorter stem (`-spec` before `-spec-status`).
    return sorted(suffixes, key=len, reverse=True)


# --- b) substitutions ---------------------------------------------------------------------------

class Rule:
    def __init__(self, name: str, pattern: bytes, repl: bytes, only: str | None = None,
                 report_sites: bool = False):
        self.name = name
        self.regex = re.compile(pattern)
        self.repl = repl
        self.only = only            # restrict to this one path
        self.report_sites = report_sites
        self.replacements = 0
        self.files: set[str] = set()
        self.sites: list[str] = []

    def apply(self, path: str, data: bytes) -> bytes:
        if self.only is not None and path != self.only:
            return data
        if self.report_sites:
            for m in self.regex.finditer(data):
                self.sites.append(f"{path}:{line_of(data, m.start())}: {line_text(data, m.start())}")
        new, n = self.regex.subn(self.repl, data)
        if n:
            self.replacements += n
            self.files.add(path)
        return new


def build_rules(suffixes: list[str]) -> list[Rule]:
    stems = b"|".join(re.escape(s.encode()) for s in suffixes)  # includes the empty stem for sdlc.md
    return [
        # 1. slash commands — never a path token (those are preceded by a word char or a dot)
        Rule("1  /sdlc -> /sprd", rb"(?<![\w./~])/sdlc\b", rb"/sprd"),
        # 2. command file paths and bare names
        Rule("2a commands/sdlc -> commands/sprd", rb"commands/sdlc", rb"commands/sprd"),
        Rule("2b command: sdlc- -> sprd-", rb"(?<=command: )('?)sdlc-", rb"\1sprd-"),
        Rule("2c anchors (#sdlc- -> (#sprd-", rb"\(#sdlc(?=-)", rb"(#sprd"),
        Rule("2d quoted \"sdlc-<cmd>.md\" -> sprd-",
             rb"(?<=[\"'`])sdlc(" + stems + rb")\.md", rb"sprd\1.md"),
        Rule("2e test_activities_model.py \"sdlc- -> \"sprd-", rb'"sdlc-', rb'"sprd-', only=ACTIVITIES_TEST),
        # 3. hook names
        Rule("3  sdlc-session-start -> shepherd-session-start", rb"sdlc-session-start", rb"shepherd-session-start"),
        # 4. hook markers — `[SDLC]`, `[SDLC-…]`, `[/SDLC-…]`; not `[SDLC profile being used]`
        Rule("4  [SDLC… -> [SHEPHERD…", rb"\[(/?)SDLC(?=[\]-])", rb"[\1SHEPHERD"),
        # 5. plugin id, most specific first
        Rule("5a MCKRUZ/claude-code-sdlc -> MCKRUZ/shepherd-sdlc", rb"MCKRUZ/claude-code-sdlc", rb"MCKRUZ/shepherd-sdlc"),
        Rule("5b claude-code-sdlc@mckruz -> shepherd@mckruz", rb"claude-code-sdlc@mckruz", rb"shepherd@mckruz"),
        Rule("5c claude-code-sdlc: -> shepherd:", rb"claude-code-sdlc:", rb"shepherd:"),
        Rule("5d bare claude-code-sdlc -> shepherd", rb"claude-code-sdlc", rb"shepherd", report_sites=True),
    ]


def build_studio_rules(suffixes: list[str]) -> list[Rule]:
    """The --studio subset: every rule here is the plugin rule of the same number, applied to
    the forms a Studio source or test file carries. No bare-id rule (see the module docstring),
    no hook rules (Studio reads no hook marker)."""
    stems = b"|".join(re.escape(s.encode()) for s in suffixes)
    return [
        Rule("S1 /sdlc -> /sprd", rb"(?<![\w./~])/sdlc\b", rb"/sprd"),
        Rule("S2a commands/sdlc -> commands/sprd", rb"commands/sdlc", rb"commands/sprd"),
        Rule("S2b command: 'sdlc- -> 'sprd-", rb"(?<=command: )('?)sdlc-", rb"\1sprd-"),
        Rule("S2d quoted 'sdlc-<cmd>.md' -> sprd-",
             rb"(?<=[\"'`])sdlc(" + stems + rb")\.md", rb"sprd\1.md"),
        Rule("S5c claude-code-sdlc: -> shepherd:", rb"claude-code-sdlc:", rb"shepherd:", report_sites=True),
        Rule("S6 pluginName: 'claude-code-sdlc' -> 'shepherd'",
             rb"(?<=pluginName: ')claude-code-sdlc(?=')", rb"shepherd"),
    ]


def main_pass_excluded(path: str) -> bool:
    return excluded(path) or path == PYPROJECT


def rewrite_tree(rules: list[Rule], dry_run: bool, skip=main_pass_excluded) -> tuple[int, int, list[str]]:
    scanned = changed = 0
    skipped_binary = []
    for path in tracked_files():
        if skip(path):
            continue
        full = ROOT / path
        if not full.is_file():
            continue
        data = full.read_bytes()
        if is_binary(data):
            skipped_binary.append(path)
            continue
        scanned += 1
        new = data
        for rule in rules:
            new = rule.apply(path, new)
        if new != data:
            changed += 1
            if not dry_run:
                full.write_bytes(new)
    return scanned, changed, skipped_binary


# --- 6) pyproject + lock -------------------------------------------------------------------------

def rewrite_pyproject(dry_run: bool) -> tuple[int, list[str]]:
    full = ROOT / PYPROJECT
    data = full.read_bytes()
    new, n_name = re.subn(rb"claude-code-sdlc-scripts", rb"shepherd-scripts", data)
    sites = []
    for m in re.finditer(rb"claude-code-sdlc", new):
        sites.append(f"{PYPROJECT}:{line_of(new, m.start())}: {line_text(new, m.start())}")
    new, n_bare = re.subn(rb"claude-code-sdlc", rb"shepherd", new)
    if new != data and not dry_run:
        full.write_bytes(new)
    return n_name + n_bare, sites


def uv_lock() -> None:
    proc = subprocess.run(["uv", "lock", "--project", "scripts"], cwd=ROOT, capture_output=True, text=True)
    if proc.returncode != 0:
        print(proc.stdout, end="")
        print(proc.stderr, end="", file=sys.stderr)
        sys.exit(f"error: `uv lock --project scripts` exited {proc.returncode}")
    print("  uv lock --project scripts: " + (proc.stderr.strip().splitlines() or ["ok"])[-1])


# --- c) report -----------------------------------------------------------------------------------

def residuals(patterns=RESIDUAL_PATTERNS, skip=excluded) -> dict[str, list[str]]:
    found: dict[str, list[str]] = {name: [] for name, _ in patterns}
    for path in tracked_files():
        if skip(path):
            continue
        full = ROOT / path
        if not full.is_file():
            continue
        data = full.read_bytes()
        if is_binary(data):
            continue
        for name, regex in patterns:
            for m in regex.finditer(data):
                found[name].append(f"{path}:{line_of(data, m.start())}: {line_text(data, m.start())}")
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true", help="report what would change; write nothing")
    parser.add_argument("--skip-lock", action="store_true", help="do not run `uv lock --project scripts`")
    parser.add_argument("--studio", action="store_true",
                        help="also rewrite the desktop app under studio/ (slash commands, command file names, "
                             "agent namespace, pluginName fixtures — never the bare plugin id)")
    args = parser.parse_args(argv)
    dry = args.dry_run

    print(f"Shepherd rename — {'DRY RUN, ' if dry else ''}repo {ROOT}")

    print("\na) moves")
    moves = command_moves() + list(HOOK_MOVES)
    moved, skipped = apply_moves(moves, dry)
    print(f"  {moved} moved, {skipped} already in place")

    suffixes = command_suffixes()
    rules = build_rules(suffixes)
    print(f"\nb) substitutions over tracked files ({len(suffixes)} command stems)")
    scanned, changed, skipped_binary = rewrite_tree(rules, dry)
    for rule in rules:
        print(f"  {rule.name:<58} {rule.replacements:>5} in {len(rule.files):>3} files")
    print(f"  files scanned: {scanned}; files changed: {changed}; binary skipped: {len(skipped_binary)}")
    for p in skipped_binary:
        print(f"    binary: {p}")

    print("\n   bare claude-code-sdlc sites (rule 5d) — review the prose around each:")
    for site in rules[-1].sites:
        print(f"    {site}")
    if not rules[-1].sites:
        print("    (none)")

    studio_rules: list[Rule] = []
    if args.studio:
        studio_rules = build_studio_rules(suffixes)
        print("\nd) --studio: substitutions over tracked files under studio/")
        s_scanned, s_changed, s_binary = rewrite_tree(studio_rules, dry, skip=studio_excluded)
        for rule in studio_rules:
            print(f"  {rule.name:<58} {rule.replacements:>5} in {len(rule.files):>3} files")
        print(f"  files scanned: {s_scanned}; files changed: {s_changed}; binary skipped: {len(s_binary)}")
        for p in s_binary:
            print(f"    binary: {p}")
        print("\n   claude-code-sdlc: sites (rule S5c) — each must be an agent name:")
        for site in studio_rules[4].sites:
            print(f"    {site}")
        if not studio_rules[4].sites:
            print("    (none)")

    print("\n6) scripts/pyproject.toml")
    n, sites = rewrite_pyproject(dry)
    print(f"  {n} replacements")
    for site in sites:
        print(f"    bare: {site}")
    if dry:
        print("  (dry run: uv lock not run)")
    elif args.skip_lock:
        print("  (--skip-lock: uv lock not run)")
    else:
        uv_lock()

    print("\nc) RESIDUALS — remaining matches in the non-excluded tracked tree")
    if dry:
        print("  (dry run: nothing was written, so the residual scan is skipped)")
        return 0
    found = residuals()
    total = 0
    for name, hits in found.items():
        print(f"  {name}: {len(hits)}")
        for h in hits:
            print(f"    {h}")
        total += len(hits)
    print(f"  total residual matches: {total}")
    if args.studio:
        print("\n   under studio/ (the --studio pass's own forms; the bare id is allowed there)")
        s_found = residuals(STUDIO_RESIDUAL_PATTERNS, skip=studio_excluded)
        s_total = 0
        for name, hits in s_found.items():
            print(f"  {name}: {len(hits)}")
            for h in hits:
                print(f"    {h}")
            s_total += len(hits)
        print(f"  total studio residual matches: {s_total}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
