#!/usr/bin/env node
// Builds docs/guide/shepherd-user-guide.html from shepherd-user-guide.template.html.
//
// Every `{{shot:<name>}}` marker in the template becomes a base64 JPEG data URI made from
// studio/test/screenshots/<SHOT_PREFIX>-<name>.png, so the guide is one self-contained file
// and the screenshots can be refreshed by re-capturing and re-running this. No dependencies;
// the conversion is macOS `sips` (resize to ≤ SHOT_WIDTH px on the long side, JPEG at
// SHOT_QUALITY), so this runs on a Mac only.
//
//   node docs/guide/build-user-guide.mjs            # reads studio/test/screenshots/observatory-v30-<name>.png
//   SHOT_PREFIX=observatory-v13 node docs/guide/build-user-guide.mjs
//   SHOT_WIDTH=1000 SHOT_QUALITY=65 node docs/guide/build-user-guide.mjs

import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..', '..')
const templatePath = join(here, 'shepherd-user-guide.template.html')
const outputPath = join(here, 'shepherd-user-guide.html')
const shotsDir = join(repoRoot, 'studio', 'test', 'screenshots')

const prefix = process.env.SHOT_PREFIX || 'observatory-v30'
const width = Number(process.env.SHOT_WIDTH || 1440)
const quality = Number(process.env.SHOT_QUALITY || 82)

const MARKER = /\{\{shot:([a-z0-9-]+)\}\}/g

function fail(message) {
  process.stderr.write(`build-user-guide: ${message}\n`)
  process.exit(1)
}

function convert(sourcePng, targetJpg) {
  const result = spawnSync(
    'sips',
    ['-s', 'format', 'jpeg', '-s', 'formatOptions', String(quality), '-Z', String(width), sourcePng, '--out', targetJpg],
    { encoding: 'utf8' },
  )
  if (result.error) fail(`could not run sips (${result.error.message}); this script needs macOS`)
  if (result.status !== 0) fail(`sips failed on ${sourcePng}:\n${result.stderr || result.stdout}`)
}

function kb(bytes) {
  return `${(bytes / 1024).toFixed(0)} KB`
}

const template = readFileSync(templatePath, 'utf8')
const names = [...new Set([...template.matchAll(MARKER)].map((m) => m[1]))]
if (names.length === 0) fail(`no {{shot:<name>}} markers found in ${templatePath}`)

const tempDir = mkdtempSync(join(tmpdir(), 'shepherd-guide-'))
const dataUris = new Map()
try {
  for (const name of names) {
    const source = join(shotsDir, `${prefix}-${name}.png`)
    try { statSync(source) } catch { fail(`screenshot not found: ${source}`) }
    const target = join(tempDir, `${name}.jpg`)
    convert(source, target)
    const bytes = readFileSync(target)
    dataUris.set(name, `data:image/jpeg;base64,${bytes.toString('base64')}`)
    process.stdout.write(`  ${prefix}-${name}.png → jpeg ${kb(bytes.length)}\n`)
  }
} finally {
  rmSync(tempDir, { recursive: true, force: true })
}

const stamp = `<!-- Generated by docs/guide/build-user-guide.mjs from shepherd-user-guide.template.html (shots: ${prefix}, ≤${width} px, q${quality}). Edit the template, not this file. -->`
// The template's own leading comment (how to build it) is replaced by the generation stamp.
const html = template
  .replace(/^(<!DOCTYPE html>\n)(?:<!--[\s\S]*?-->\n)?/, `$1${stamp}\n`)
  .replace(MARKER, (_, name) => dataUris.get(name))

writeFileSync(outputPath, html)
const size = statSync(outputPath).size
process.stdout.write(`wrote ${outputPath}\n${names.length} screenshots inlined · final size ${kb(size)} (${(size / 1024 / 1024).toFixed(2)} MB)\n`)
